// Generates the TS files of the schemas (projects/schema/src/lib/*.schema.ts) from the JSON files, which stay the only
// source, and the precompiled validators (projects/schema/src/lib/validators.generated.ts, Ajv "standalone"): nothing is
// compiled in the browser, so no `new Function` (the Content-Security-Policy does not need 'unsafe-eval') and no Ajv
// compiler in the bundle.
// Usage: node tools/sync-schema.mjs [--check]   (with --check it writes nothing: it fails if the files are not aligned)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

const here = dirname(fileURLToPath(import.meta.url));
const lib = join(here, '../projects/schema/src/lib');
const schemas = [
  { name: 'screen', constant: 'SCREEN_SCHEMA' },
  { name: 'theme', constant: 'THEME_SCHEMA' },
  { name: 'navigation', constant: 'NAVIGATION_SCHEMA' },
  { name: 'messages', constant: 'MESSAGES_SCHEMA' },
  { name: 'datasources', constant: 'DATASOURCES_SCHEMA' },
  { name: 'project', constant: 'PROJECT_SCHEMA' },
];
const check = process.argv.includes('--check');
let misaligned = 0;

for (const { name, constant } of schemas) {
  const schema = JSON.parse(readFileSync(join(lib, `schemas/${name}.schema.json`), 'utf8'));
  const target = join(lib, `${name}.schema.ts`);
  const content =
    `// GENERATED by tools/sync-schema.mjs from schemas/${name}.schema.json: do not edit by hand.\n` +
    '// After every change to the schema: npm run schema:sync\n' +
    `export const ${constant}: Record<string, unknown> = ${JSON.stringify(schema, null, 2)};\n`;
  if (check) {
    const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
    if (current !== content) {
      console.error(`${name}.schema.ts is not aligned with ${name}.schema.json: run npm run schema:sync`);
      misaligned++;
    }
  } else {
    writeFileSync(target, content);
    console.log(`Generated ${name}.schema.ts`);
  }
}
// Precompiled validators: the same options (all errors, strict mode), one source with one export per schema.
{
  const ajv = new Ajv2020({ allErrors: true, strict: true, code: { source: true, esm: true, lines: false } });
  const exportsByName = {};
  for (const { name } of schemas) {
    const schema = JSON.parse(readFileSync(join(lib, `schemas/${name}.schema.json`), 'utf8'));
    ajv.addSchema(withoutAnnotations(schema));
    exportsByName[`${name}Validator`] = schema.$id;
  }
  let code = standaloneCode(ajv, exportsByName);
  // The only Ajv runtime dependency in use (length of a string in Unicode characters) becomes a local function: the file
  // imports nothing.
  code = code.replace(/const (\w+) = require\("ajv\/dist\/runtime\/ucs2length"\)\.default;?/g, 'const $1 = (s) => [...s].length;');
  if (/require\(/.test(code)) throw new Error('validators: unexpected runtime dependency');
  code = withoutUnusedSchemas(code);
  // Each error is collected by the same four statements (more than a thousand times): one shared function instead.
  const collect = /const (err\d+) = (\{[\s\S]*?\});if\(vErrors === null\)\{vErrors = \[\1\];\}else \{vErrors\.push\(\1\);\}/g;
  code = code.replace(collect, 'vErrors = pushError(vErrors, $2);');
  if (code.includes('if(vErrors === null){vErrors = [err') || !code.startsWith('"use strict";')) throw new Error('validators: unexpected form of the generated code');
  code = '"use strict";const pushError = (errors, error) => { if (errors === null) return [error]; errors.push(error); return errors; };' + code.slice('"use strict";'.length);
  const content =
    '// GENERATED by tools/sync-schema.mjs from schemas/*.schema.json: do not edit by hand.\n' +
    '// After every change to the schemas: npm run schema:sync\n' +
    '/* eslint-disable */\n// @ts-nocheck\n' +
    code +
    '\n';
  const target = join(lib, 'validators.generated.ts');
  if (check) {
    const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
    if (current !== content) {
      console.error('validators.generated.ts is not aligned with the schemas: run npm run schema:sync');
      misaligned++;
    }
  } else {
    writeFileSync(target, content);
    console.log('Generated validators.generated.ts');
  }
}
if (check) {
  if (misaligned) process.exit(1);
  console.log('Schemas aligned.');
}

// The validators embed the schemas they read the enums from: the annotations (description, title) do not change the
// validation, so they stay out of the bundle. The keys of `properties` and `$defs` are names, not keywords; the values of
// `enum`, `const` and `required` are data.
function withoutAnnotations(schema) {
  if (Array.isArray(schema)) return schema.map(withoutAnnotations);
  if (!schema || typeof schema !== 'object') return schema;
  const result = {};
  for (const [key, value] of Object.entries(schema)) {
    if (key === 'description' || key === 'title') continue;
    if (key === 'properties' || key === 'patternProperties' || key === '$defs' || key === 'dependentSchemas') {
      result[key] = Object.fromEntries(Object.entries(value).map(([name, sub]) => [name, withoutAnnotations(sub)]));
    } else {
      result[key] = key === 'enum' || key === 'const' || key === 'default' || key === 'required' ? value : withoutAnnotations(value);
    }
  }
  return result;
}

// Ajv standalone declares every compiled schema (`const schema12 = {…};`) even when the code never reads it.
function withoutUnusedSchemas(code) {
  const declaration = /const (schema\d+) = \{/g;
  const unused = [];
  for (const match of code.matchAll(declaration)) {
    if (code.split(new RegExp(`\\b${match[1]}\\b`)).length === 2) unused.push({ start: match.index, end: endOfObject(code, match.index + match[0].length - 1) });
  }
  for (const { start, end } of unused.reverse()) code = code.slice(0, start) + code.slice(code[end] === ';' ? end + 1 : end);
  return code;
}

// Index just after the JSON object that opens at `start`.
function endOfObject(code, start) {
  let depth = 0;
  for (let i = start; i < code.length; i++) {
    const c = code[i];
    if (c === '"') {
      for (i++; code[i] !== '"'; i++) if (code[i] === '\\') i++;
    } else if (c === '{' || c === '[') depth++;
    else if ((c === '}' || c === ']') && --depth === 0) return i + 1;
  }
  throw new Error('validators: unterminated schema');
}
