// Generates the TS files of the schemas (projects/schema/src/lib/*.schema.ts) from the JSON files, which stay the only
// source, and the precompiled validators (projects/schema/src/lib/validators.generated.ts, Ajv "standalone"): nothing is
// compiled in the browser, so no `new Function` (the Content-Security-Policy does not need 'unsafe-eval') and no Ajv
// compiler in the bundle.
// Usage: node tools/sync-schema.mjs [--check]   (with --check it writes nothing: it fails if the files are not aligned)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

const here = dirname(fileURLToPath(import.meta.url));
const lib = join(here, '../projects/schema/src/lib');
const schemas = [
  { name: 'screen', constant: 'SCREEN_SCHEMA' },
  { name: 'theme', constant: 'THEME_SCHEMA' },
  { name: 'navigation', constant: 'NAVIGATION_SCHEMA' },
  { name: 'messages', constant: 'MESSAGES_SCHEMA' },
];
const check = process.argv.includes('--check');
let misaligned = 0;

for (const { name, constant } of schemas) {
  const schema = JSON.parse(readFileSync(join(lib, `schemas/${name}.schema.json`), 'utf8'));
  const target = join(lib, `${name}.schema.ts`);
  const content =
    `// GENERATED by tools/sync-schema.mjs from schemas/${name}.schema.json: do not edit by hand.\n` +
    '// After every change to the schema: npm run schema:sync\n' +
    `export const ${constant}: Record<string, unknown> = ${JSON.stringify(schema, null, 2)};\n`;
  if (check) {
    const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
    if (current !== content) {
      console.error(`${name}.schema.ts is not aligned with ${name}.schema.json: run npm run schema:sync`);
      misaligned++;
    }
  } else {
    writeFileSync(target, content);
    console.log(`Generated ${name}.schema.ts`);
  }
}
// Precompiled validators: the same options (all errors, strict mode), one source with one export per schema.
{
  const ajv = new Ajv2020({ allErrors: true, strict: true, code: { source: true, esm: true, lines: false } });
  const exportsByName = {};
  for (const { name } of schemas) {
    const schema = JSON.parse(readFileSync(join(lib, `schemas/${name}.schema.json`), 'utf8'));
    ajv.addSchema(schema);
    exportsByName[`${name}Validator`] = schema.$id;
  }
  let code = standaloneCode(ajv, exportsByName);
  // The only Ajv runtime dependency in use (length of a string in Unicode characters) becomes a local function: the file
  // imports nothing.
  code = code.replace(/const (\w+) = require\("ajv\/dist\/runtime\/ucs2length"\)\.default;?/g, 'const $1 = (s) => [...s].length;');
  if (/require\(/.test(code)) throw new Error('validators: unexpected runtime dependency');
  const content =
    '// GENERATED by tools/sync-schema.mjs from schemas/*.schema.json: do not edit by hand.\n' +
    '// After every change to the schemas: npm run schema:sync\n' +
    '/* eslint-disable */\n// @ts-nocheck\n' +
    code +
    '\n';
  const target = join(lib, 'validators.generated.ts');
  if (check) {
    const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
    if (current !== content) {
      console.error('validators.generated.ts is not aligned with the schemas: run npm run schema:sync');
      misaligned++;
    }
  } else {
    writeFileSync(target, content);
    console.log('Generated validators.generated.ts');
  }
}
if (check) {
  if (misaligned) process.exit(1);
  console.log('Schemas aligned.');
}
