// Writes frontend/THIRD-PARTY-NOTICES.md: the packages shipped in the browser bundles (the production
// dependencies of the workspace and theirs), with version, licence and licence text, as their licences require.
//   node tools/third-party-notices.mjs            write the file
//   node tools/third-party-notices.mjs --check    fail if the file is not up to date (CI)
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const target = join(root, 'THIRD-PARTY-NOTICES.md');
const LICENCE_FILE = /^(licen[cs]e|copying|notice)(\.(md|txt|markdown))?$/i;

/** The package directory as Node resolves it from `from`: the nearest node_modules going up. */
function resolve(name, from) {
  for (let dir = from; ; dir = dirname(dir)) {
    const candidate = join(dir, 'node_modules', name);
    if (existsSync(join(candidate, 'package.json'))) return candidate;
    if (dirname(dir) === dir) return null;
  }
}

const found = new Map();
function visit(name, from) {
  const dir = resolve(name, from);
  if (!dir) return;
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const id = `${pkg.name}@${pkg.version}`;
  if (found.has(id)) return;
  const files = readdirSync(dir).filter((f) => LICENCE_FILE.test(f)).sort();
  const licence = typeof pkg.license === 'string' ? pkg.license : (pkg.license?.type ?? (pkg.licenses ?? []).map((l) => l.type).join(' OR ')) || 'UNKNOWN';
  const repository = typeof pkg.repository === 'string' ? pkg.repository : (pkg.repository?.url ?? pkg.homepage ?? '');
  found.set(id, { name: pkg.name, version: pkg.version, licence, repository, texts: files.map((f) => readFileSync(join(dir, f), 'utf8').replace(/\r\n/g, '\n').trim()) });
  for (const dep of Object.keys(pkg.dependencies ?? {})) visit(dep, dir);
}

const workspace = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
for (const dep of Object.keys(workspace.dependencies ?? {})) visit(dep, root);

const packages = [...found.values()].sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
const lines = [
  '# Third-party notices',
  '',
  'Quadrava (MPL-2.0, see LICENSE) ships the following third-party packages in its browser bundles. This file is generated by',
  '`frontend/tools/third-party-notices.mjs` from the production dependencies of `frontend/package.json`: do not edit it by hand.',
  'The reference services in `reference/` are distributed as source only; their Maven dependencies keep their own licences.',
  '',
  '| Package | Version | Licence |',
  '| --- | --- | --- |',
  ...packages.map((p) => `| ${p.name} | ${p.version} | ${p.licence} |`),
  '',
];
for (const p of packages) {
  lines.push(`## ${p.name} ${p.version}`, '', `Licence: ${p.licence}${p.repository ? ` · Source: ${p.repository.replace(/^git\+/, '')}` : ''}`, '');
  if (p.texts.length) for (const text of p.texts) lines.push('```text', text, '```', '');
  else lines.push('(No licence file in the package: see the licence named above.)', '');
}
const content = lines.join('\n');

if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (current !== content) {
    console.error('THIRD-PARTY-NOTICES.md is not up to date: run npm run notices');
    process.exit(1);
  }
  console.log(`Third-party notices up to date (${packages.length} packages).`);
} else {
  writeFileSync(target, content);
  console.log(`THIRD-PARTY-NOTICES.md: ${packages.length} packages.`);
}
