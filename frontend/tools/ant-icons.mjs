// Writes projects/components/src/lib/ant-icon-names.generated.ts: the names of the Ant Design icons, outlined and filled,
// that the runtime serves as static files (assets/outline/<name>.svg, assets/fill/<name>.svg, copied from
// @ant-design/icons-angular by angular.json). Only these names are ever fetched: the list and the files come from the
// same package, so a name on the list always has its file (ADR-29).
//   node tools/ant-icons.mjs            write the file
//   node tools/ant-icons.mjs --check    fail if the file is not up to date (CI)
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const pkg = join(root, 'node_modules/@ant-design/icons-angular');
const target = join(root, 'projects/components/src/lib/ant-icon-names.generated.ts');
const version = JSON.parse(readFileSync(join(pkg, 'package.json'), 'utf8')).version;

const names = (theme) =>
  readdirSync(join(pkg, 'src/inline-svg', theme))
    .filter((f) => f.endsWith('.svg'))
    .map((f) => f.slice(0, -4))
    .sort();
const outlined = names('outline');
const filled = names('fill');
const valid = /^[a-z0-9]+(-[a-z0-9]+)*$/;
for (const name of [...outlined, ...filled]) if (!valid.test(name)) throw new Error(`unexpected icon name: ${name}`);

const content = `// Generated by tools/ant-icons.mjs from @ant-design/icons-angular ${version}: do not edit.
// The Ant Design icons served as static files (assets/outline, assets/fill): only these names are fetched.

/** Names of the outlined icons, in alphabetical order. */
export const ANT_OUTLINED: readonly string[] = ${JSON.stringify(outlined.join(' '))}.split(' ');

/** Names of the icons that also have a filled form, in alphabetical order. */
export const ANT_FILLED: readonly string[] = ${JSON.stringify(filled.join(' '))}.split(' ');
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {
    // Missing: not up to date.
  }
  if (current !== content) {
    console.error(`${target} is not up to date: run npm run icons`);
    process.exit(1);
  }
  console.log('ant-icon-names.generated.ts is up to date');
} else {
  writeFileSync(target, content);
  console.log(`Wrote ${target} (${outlined.length} outlined, ${filled.length} filled)`);
}
