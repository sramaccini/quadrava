// Generates docs/schema-reference.md from the descriptions in the JSON schemas (projects/schema/src/lib/schemas): for
// every component and every step, its properties with type, whether required, and description. The schemas remain the
// only source; this file is just a readable view.
//
//   node tools/schema-docs.mjs [--check]   (with --check nothing is written: fails if the document is out of date)
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const schemas = join(here, '../projects/schema/src/lib/schemas');
const target = join(here, '../../docs/schema-reference.md');
const read = (name) => JSON.parse(readFileSync(join(schemas, `${name}.schema.json`), 'utf8'));
const screen = read('screen');
const defs = screen.$defs;

/** Text on one line, with vertical bars escaped (we are inside a Markdown table). */
const cell = (text) => String(text ?? '').replace(/\s+/g, ' ').replaceAll('|', '\\|').trim();

/** Readable type of a property. */
function typeOf(schema) {
  if (!schema) return '';
  if (schema.$ref) {
    const name = schema.$ref.split('/').pop();
    if (name === 'node') return 'component';
    if (name === 'expression') return 'expression';
    if (name === 'statePath') return 'state path';
    if (name === 'step') return 'step';
    return name;
  }
  if (schema.enum) return schema.enum.map((v) => `\`${v}\``).join(', ');
  if (schema.const !== undefined) return `\`${JSON.stringify(schema.const)}\``;
  if (schema.anyOf) return schema.anyOf.map(typeOf).join(' or ');
  if (schema.type === 'array') return `list of ${typeOf(schema.items) || 'values'}`;
  if (schema.type === 'object') return 'object';
  if (schema.type === 'string') return 'text';
  if (schema.type === 'integer') return `integer${schema.minimum !== undefined ? ` ${schema.minimum}–${schema.maximum ?? '…'}` : ''}`;
  if (schema.type === 'number') return 'number';
  if (schema.type === 'boolean') return 'yes/no';
  return '';
}

/** Description: the property's own or, if missing, that of the definition it refers to. */
function describe(schema) {
  if (schema?.description) return schema.description;
  if (schema?.$ref) return defs[schema.$ref.split('/').pop()]?.description ?? '';
  return '';
}

function table(properties, required = []) {
  const rows = Object.entries(properties).map(([name, schema]) => `| \`${name}\`${required.includes(name) ? ' *' : ''} | ${cell(typeOf(schema))} | ${cell(describe(schema))} |`);
  return ['| Property | Type | Description |', '| --- | --- | --- |', ...rows].join('\n');
}

const out = [];
out.push('# KinetiX screen schema reference');
out.push('');
out.push(
  '> Generated by `frontend/tools/schema-docs.mjs` from `screen.schema.json`: do not edit by hand. After changing the schema: `npm run schema:docs`. Properties marked * are required. Explanations with examples are in the [component catalogue](component-catalogue.md).',
);
out.push('');
out.push('## Properties common to all components');
out.push('');
const common = { ...defs.node.properties };
delete common.type;
out.push(table(common));
out.push('');
out.push('## Components');
for (const branch of defs.node.allOf) {
  const type = branch.if.properties.type.const;
  const then = branch.then;
  out.push('');
  out.push(`### \`${type}\``);
  out.push('');
  out.push(table(then.properties ?? {}, then.required ?? []));
}
out.push('');
out.push('## Action steps');
for (const ref of defs.step.oneOf) {
  const name = ref.$ref.split('/').pop();
  const step = defs[name];
  const key = (step.required ?? [])[0];
  out.push('');
  out.push(`### \`${key}\``);
  out.push('');
  out.push(table(step.properties ?? {}, step.required ?? []));
}
out.push('');
out.push('## Fields (forms, filters, standalone fields)');
out.push('');
out.push(table(defs.field.properties, defs.field.required));
out.push('');
out.push('## Data sources');
out.push('');
const ds = defs.dataSource;
out.push(table(ds.properties ?? {}, ds.required ?? []));
out.push('');
const content = out.join('\n');

if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (current !== content) {
    console.error('docs/schema-reference.md is out of date: run npm run schema:docs');
    process.exit(1);
  }
  console.log('Schema reference up to date.');
} else {
  writeFileSync(target, content);
  console.log('Generated docs/schema-reference.md');
}
